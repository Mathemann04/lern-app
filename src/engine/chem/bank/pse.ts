const elementLabel = (symbol: string) => `${elementBySymbol(symbol)!.name} ($\\ce{${symbol}}$)`
const KIND_NAMES: Readonly<Record<Kind, string>> = { metall: 'Metall', halbmetall: 'Halbmetall', nichtmetall: 'Nichtmetall' }
